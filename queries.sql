-- Задание 1. Самый дорогой товар
-- Выводим название и цену, сортируем по убыванию цены и берем первую строку.
SELECT название, цена FROM Товар ORDER BY цена DESC LIMIT 1;

-- Задание 2. Самый дешёвый товар
-- Выводим название и цену, сортируем по возрастанию цены и берем первую строку.
SELECT название, цена FROM Товар ORDER BY цена ASC LIMIT 1;

-- Задание 3. Товары категории «Электроника» (замените на вашу категорию)
-- Выводим товары, где столбец категория совпадает с указанным значением.
SELECT название, цена FROM Товар WHERE категория = 'Электроника';

-- Задание 4. Поиск по названию (есть буква «о»)
-- Используем оператор LIKE и знак % для поиска подстроки в любом месте названия.
SELECT * FROM Товар WHERE название LIKE '%о%';

-- Задание 5. Все заказы
-- Выводим конкретные столбцы из таблицы Заказ.
SELECT id, дата, клиент, товар_id, количество FROM Заказ;

-- Задание 6. Заказы конкретного клиента
-- Ищем записи, где клиент точно совпадает с искомым ФИО.
SELECT * FROM Заказ WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями товаров
-- Связываем таблицы Заказ и Товар по ID товара, чтобы вывести название вместо номера.
SELECT Заказ.дата, Заказ.клиент, Товар.название, Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
-- Умножаем цену товара на количество в заказе и суммируем все строки.
SELECT SUM(Товар.цена * Заказ.количество) AS итоговая_сумма
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
-- Группируем по клиенту и считаем количество строк (заказов) для каждого.
SELECT клиент, COUNT(*) AS количество_заказов
FROM Заказ
GROUP BY клиент;

-- Задание 10. Мой запрос
-- Что хочу получить: Список товаров, которых на складе осталось меньше 5 штук (для пополнения запасов).
SELECT название, количество FROM Товар WHERE количество < 5;
